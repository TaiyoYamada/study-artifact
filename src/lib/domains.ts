/**
 * トップレベルの分野ごとの色相。
 *
 * 500 本を超える木の中で「いま自分がどの分野にいるか」を示すために使う。
 * 装飾ではなく現在地の手がかりなので、出すのはパンくず・見出しの罫・
 * ツリーの目印だけに絞り、本文とリンクの色は全分野で共通のままにする。
 *
 * 値は HSL の色相 (0-360)。彩度と明度はテーマ側で決まる。
 */
const HUES: Record<string, number> = {
	数学: 231,
	最適化: 178,
	コンピュータ: 205,
	人工知能: 268,
	量子力学: 244,
	量子情報: 194,
	量子化学: 150,
	量子コンピューティング: 283,
	量子アルゴリズム: 316,
	量子シミュレーション: 166,
	量子誤り訂正: 12,
	ソフトウェア開発: 38,
	科学計算: 82,
	研究: 218,
	論文メモ: 340
};

/** 既定はサイト全体のアクセスと同じ青。分野が決まらないページで使う。 */
const DEFAULT_HUE = 224;

/** slug の先頭の階層から色相を引く。 例: `数学/線形代数/行列` → 数学の色相 */
export function domainHue(slug: string): number {
	const top = slug.split('/')[0] ?? '';
	return HUES[top] ?? DEFAULT_HUE;
}

export function domainName(slug: string): string {
	return slug.split('/')[0] ?? '';
}
